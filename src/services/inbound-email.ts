// Emails entrants — Cloudflare Email Routing → Email Worker → ici, et relève IMAP
// de la boîte de contact (services/mailbox.ts).
//
// parseRawEmail : parseur MIME volontairement minimal mais sûr — en-têtes dépliés,
// multipart imbriqué (délimiteurs reconnus en début de ligne seulement), text/plain
// préféré au HTML, pièces jointes listées (jamais lues comme corps), quoted-printable,
// base64, 7bit/8bit avec le bon charset, encoded-words RFC 2047, paramètres RFC 2231 —
// sans dépendance.
//
// processInboundEmail : stocke le mail, le rattache au client/à la résa
// (référence PM-2026-001 dans le sujet/corps, sinon email de l'expéditeur),
// envoie l'accusé de réception automatique (si activé dans Paramètres — OFF
// par défaut) et transfère vers l'adresse personnelle configurée. Idempotent
// par Message-ID (les re-livraisons ne créent pas de doublon).

