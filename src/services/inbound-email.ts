export interface MailAttachment {
  name: string;
  /** Taille décodée en octets ; null si le message a été coupé avant la fin. */
  size: number | null;
}

export interface ParsedEmail {
  messageId: string | null;
  from: string;
  fromName: string | null;
  to: string | null;
  subject: string;
  textBody: string;
  isAutoGenerated: boolean;
  /** Message-ID auquel ce mail répond (un seul identifiant, forme <…>). */
  inReplyTo?: string | null;
  /** Fil : identifiants de References, séparés par une espace (20 derniers). */
  references?: string | null;
  /** Date de l'en-tête Date, en ISO ; null si absente ou illisible. */
  date?: string | null;
  attachments?: MailAttachment[];
  /** Le serveur de réception (Gmail) atteste l'expéditeur : DMARC ou DKIM « pass ». */
  senderAuthenticated?: boolean;
  /** Adresse réellement destinataire (Delivered-To), sinon null. */
  deliveredTo?: string | null;
  /** Le message a été coupé à la relève (trop gros) : corps et pièces possiblement incomplets. */
  truncated?: boolean;
}

/** Corps de texte gardé au plus (le reste est coupé, avec une mention). */
export const MAX_TEXT_BODY = 20000;
const MAX_MIME_DEPTH = 6;

/** Retire tout caractère de contrôle (et séparateurs de ligne Unicode) d'une valeur d'en-tête. */
function cleanHeader(value: string): string {
  return value.replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, " ").replace(/\s{2,}/g, " ").trim();
}

function unfoldHeaders(rawHeaders: string): Map<string, string> {
  const map = new Map<string, string>();
  const lines = rawHeaders.split(/\r?\n/);
  let current = "";
  const flush = () => {
    if (!current) return;
    const idx = current.indexOf(":");
    if (idx > 0) {
      const name = current.slice(0, idx).trim().toLowerCase();
      const value = current.slice(idx + 1).trim();
      if (!map.has(name)) map.set(name, value);
    }
    current = "";
  };
  for (const line of lines) {
    if (/^[ \t]/.test(line)) {
      current += " " + line.trim();
    } else {
      flush();
      current = line;
    }
  }
  flush();
  return map;
}

/** Décode les encoded-words RFC 2047 : =?utf-8?B?…?= / =?iso-8859-1?Q?…?= */
export function decodeEncodedWords(value: string): string {
  // deux mots encodés qui se suivent (repliement) : l'espace entre eux est supprimée (RFC 2047 § 6.2)
  const joined = value.replace(/(\?=)\s+(?==\?[^?]+\?[bBqQ]\?)/g, "$1");
  return joined.replace(/=\?([^?]+)\?([bBqQ])\?([^?]*)\?=/g, (_m, charset: string, enc: string, text: string) => {
    try {
      const bytes =
        enc.toUpperCase() === "B"
          ? base64ToBytes(text)
          : qpToBytes(text.replace(/_/g, " "), true);
      return decodeBytes(bytes, charset.replace(/\*.*$/, ""));
    } catch {
      return text;
    }
  });
}

function base64ToBytes(b64: string): Uint8Array {
  let clean = b64.replace(/[^A-Za-z0-9+/]/g, "");
  // base64 coupé : atob refuse une longueur % 4 == 1
  if (clean.length % 4 === 1) clean = clean.slice(0, -1);
  const bin = atob(clean + "=".repeat((4 - (clean.length % 4)) % 4));
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

function qpToBytes(text: string, header = false): Uint8Array {
  // quoted-printable : =XX, soft line breaks =\r?\n (espaces éventuelles avant le saut)
  const src = header ? text : text.replace(/=[ \t]*\r?\n/g, "");
  const out: number[] = [];
  const enc = new TextEncoder();
  for (let i = 0; i < src.length; i++) {
    const c = src[i]!;
    if (c === "=" && /^[0-9A-Fa-f]{2}$/.test(src.slice(i + 1, i + 3))) {
      out.push(parseInt(src.slice(i + 1, i + 3), 16));
      i += 2;
    } else {
      const code = c.charCodeAt(0);
      if (code <= 0xff) out.push(code);
      else for (const b of enc.encode(c)) out.push(b);
    }
  }
  return new Uint8Array(out);
}

function decodeBytes(bytes: Uint8Array, charset: string): string {
  const cs = charset.trim().replace(/^["']|["']$/g, "").toLowerCase();
  try {
    return new TextDecoder(cs === "us-ascii" || cs === "" ? "utf-8" : cs).decode(bytes);
  } catch {
    return new TextDecoder("utf-8").decode(bytes);
  }
}

/** Chaîne « binaire » (un caractère = un octet) → octets. */
function binaryToBytes(s: string): Uint8Array {
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i) & 0xff;
  return out;
}

/** En-tête reçu en mode binaire : de l'UTF-8 brut (non conforme mais courant) est relu comme tel. */
function fixBinaryHeader(value: string): string {
  if (!/[\u0080-ÿ]/.test(value)) return value;
  try {
    return new TextDecoder("utf-8", { fatal: true, ignoreBOM: false }).decode(binaryToBytes(value));
  } catch {
    return value;
  }
}

/** Décode une valeur RFC 2231 (charset'langue'%XX) ; sans charset, les %XX sont lus en UTF-8. */
function decodeExtValue(value: string): string {
  const ext = /^([^']*)'[^']*'(.*)$/.exec(value);
  const charset = ext ? ext[1] || "utf-8" : "utf-8";
  const encoded = ext ? ext[2]! : value;
  try {
    const pct = encoded.replace(/%([0-9A-Fa-f]{2})/g, (_x, h: string) => String.fromCharCode(parseInt(h, 16)));
    return decodeBytes(binaryToBytes(pct), charset);
  } catch {
    return value;
  }
}

/** Paramètre coupé en segments (filename*0=… filename*1*=…), RFC 2231 § 3 : on recolle dans l'ordre. */
function continuedParam(headerValue: string, param: string): string | null {
  const re = new RegExp(`(?:^|[;\\s])${param}\\*(\\d+)(\\*?)\\s*=\\s*(?:"((?:[^"\\\\]|\\\\.)*)"|([^;\\s]*))`, "gi");
  const segs = new Map<number, { encoded: boolean; value: string }>();
  for (const m of headerValue.matchAll(re)) {
    const index = Number(m[1]);
    if (index > 50 || segs.has(index)) continue;
    segs.set(index, { encoded: m[2] === "*", value: m[3] !== undefined ? m[3].replace(/\\(.)/g, "$1") : (m[4] ?? "") });
  }
  if (!segs.size) return null;
  // segments contigus depuis 0 : au premier trou, la suite est ignorée (jamais un nom recollé de travers)
  const ordered: [number, { encoded: boolean; value: string }][] = [];
  for (let i = 0; segs.has(i); i++) ordered.push([i, segs.get(i)!]);
  if (!ordered.length) return null;
  // le charset n'est annoncé que dans le premier segment encodé
  const first = ordered[0]![1];
  const head = first.encoded ? /^([^']*'[^']*')/.exec(first.value)?.[1] ?? "" : "";
  const joined = ordered.map(([, s], i) => (s.encoded ? (i === 0 ? s.value.slice(head.length) : s.value) : encodeURIComponent(s.value).replace(/'/g, "%27"))).join("");
  const out = (head ? decodeExtValue(head + joined) : decodeExtValue(joined)).trim();
  return out || null;
}

/** Valeur d'un paramètre d'en-tête (name="…", name=…, name*=utf-8''%C3%A9 et segments de la RFC 2231). */
function headerParam(headerValue: string, param: string): string | null {
  const re = new RegExp(`(?:^|[;\\s])${param}(\\*?)\\s*=\\s*(?:"((?:[^"\\\\]|\\\\.)*)"|([^;\\s]*))`, "i");
  const m = re.exec(headerValue);
  if (!m) return continuedParam(headerValue, param);
  let value = m[2] !== undefined ? m[2].replace(/\\(.)/g, "$1") : (m[3] ?? "");
  if (m[1] === "*") value = decodeExtValue(value);
  value = value.trim();
  return value || null;
}

interface MimePart {
  headers: Map<string, string>;
  body: string;
}

/** Sépare un multipart. Les délimiteurs ne comptent qu'en début de ligne : un « --boundary »
 *  cité au milieu d'une phrase ne coupe rien ; ce qui suit le délimiteur de fin est ignoré. */
function splitParts(body: string, boundary: string): MimePart[] {
  const delim = `--${boundary}`;
  const chunks: string[][] = [];
  let cur: string[] | null = null;
  for (const line of body.split(/\r?\n/)) {
    const t = line.replace(/[ \t]+$/, "");
    if (t === delim) {
      if (cur) chunks.push(cur);
      cur = [];
    } else if (t === `${delim}--`) {
      if (cur) chunks.push(cur);
      cur = null;
      break;
    } else if (cur) {
      cur.push(line);
    }
  }
  if (cur) chunks.push(cur);
  return chunks.map((lines) => {
    const blank = lines.findIndex((l) => l === "");
    if (blank < 0) return { headers: unfoldHeaders(lines.join("\n")), body: "" };
    return { headers: unfoldHeaders(lines.slice(0, blank).join("\n")), body: lines.slice(blank + 1).join("\n") };
  });
}

function decodeBody(body: string, headers: Map<string, string>, binary: boolean): string {
  const cte = (headers.get("content-transfer-encoding") ?? "").trim().toLowerCase();
  const charset = headerParam(headers.get("content-type") ?? "", "charset") ?? "utf-8";
  try {
    if (cte === "base64") return decodeBytes(base64ToBytes(body), charset);
    if (cte === "quoted-printable") return decodeBytes(qpToBytes(body), charset);
  } catch {
    return "";
  }
  // 7bit / 8bit / binary : en mode binaire, relire les octets avec le charset annoncé
  return binary ? decodeBytes(binaryToBytes(body), charset) : body;
}

/** Taille décodée d'une pièce, à partir du corps encodé. */
function decodedSize(body: string, headers: Map<string, string>): number {
  const cte = (headers.get("content-transfer-encoding") ?? "").trim().toLowerCase();
  if (cte === "base64") {
    const clean = body.replace(/[^A-Za-z0-9+/]/g, "");
    return Math.floor((clean.length * 3) / 4);
  }
  if (cte === "quoted-printable") return qpToBytes(body).length;
  return body.length;
}

interface Collected {
  plain: string[];
  html: string[];
  attachments: MailAttachment[];
}

function collect(
  body: string,
  headers: Map<string, string>,
  out: Collected,
  ctx: { binary: boolean; truncated: boolean },
  depth: number,
): void {
  const rawType = headers.get("content-type") ?? "text/plain";
  const type = rawType.split(";")[0]!.trim().toLowerCase();
  const disposition = (headers.get("content-disposition") ?? "").toLowerCase();
  const filename = headerParam(headers.get("content-disposition") ?? "", "filename") ?? headerParam(rawType, "name");
  const name = filename ? cleanHeader(decodeEncodedWords(ctx.binary ? fixBinaryHeader(filename) : filename)).slice(0, 200) : null;

  if (type.startsWith("multipart/")) {
    const boundary = headerParam(rawType, "boundary");
    if (boundary && depth < MAX_MIME_DEPTH) {
      for (const p of splitParts(body, boundary)) collect(p.body, p.headers, out, ctx, depth + 1);
    }
    return;
  }
  const isText = type === "text/plain" || type === "text/html";
  const isAttachment =
    disposition.startsWith("attachment") ||
    type.startsWith("message/") ||
    (name != null && !isText && !disposition.startsWith("inline"));
  if (!isAttachment && type === "text/plain") {
    out.plain.push(decodeBody(body, headers, ctx.binary));
    return;
  }
  if (!isAttachment && type === "text/html") {
    out.html.push(htmlToText(decodeBody(body, headers, ctx.binary)));
    return;
  }
  if (isAttachment || name != null) {
    out.attachments.push({ name: name ?? `(${type})`, size: ctx.truncated ? null : decodedSize(body, headers) });
  }
}

const ENTITIES: Record<string, string> = {
  nbsp: " ", amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", euro: "€", hellip: "…", ndash: "–", mdash: "—",
  rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", laquo: "«", raquo: "»", copy: "©", deg: "°",
  eacute: "é", egrave: "è", ecirc: "ê", euml: "ë", agrave: "à", acirc: "â", ocirc: "ô", ugrave: "ù", ucirc: "û",
  icirc: "î", iuml: "ï", ccedil: "ç", Eacute: "É", Egrave: "È", Agrave: "À", Ccedil: "Ç",
};

function decodeEntities(s: string): string {
  return s.replace(/&(#x[0-9a-fA-F]+|#\d+|[a-zA-Z]+);/g, (m, e: string) => {
    if (e[0] === "#") {
      const code = e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      const control = code < 32 && code !== 10 && code !== 9;
      if (!Number.isFinite(code) || control || code > 0x10ffff || (code >= 0xd800 && code <= 0xdfff)) return " ";
      return String.fromCodePoint(code);
    }
    return ENTITIES[e] ?? m;
  });
}

/** HTML → texte brut. Les liens gardent leur cible entre parenthèses (le texte d'un lien peut
 *  mentir sur sa destination) ; rien n'est interprété : le résultat n'est que du texte. */
export function htmlToText(html: string): string {
  return decodeEntities(
    html
      .replace(/<!--[\s\S]*?-->/g, " ")
      .replace(/<(style|script|head|title)\b[\s\S]*?<\/\1\s*>/gi, " ")
      .replace(
        /<a\b[^>]*?\bhref\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))[^>]*>([\s\S]*?)<\/a\s*>/gi,
        (_m, a?: string, b?: string, c?: string, label = "") => {
          const href = decodeEntities((a ?? b ?? c ?? "").trim());
          const text = (label as string).replace(/<[^>]+>/g, "").trim();
          if (!/^https?:\/\//i.test(href) || href.length > 300) return text;
          return text === href || text === "" ? href : `${text} (${href})`;
        },
      )
      .replace(/<br\s*\/?>/gi, "\n")
      .replace(/<li\b[^>]*>/gi, "\n- ")
      .replace(/<\/(p|div|tr|li|h[1-6]|table|blockquote)\s*>/gi, "\n")
      .replace(/<[^>]*>/g, ""),
  )
    .replace(/[ \t\f\v ]+/g, " ")
    .replace(/ *\n */g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function parseAddress(value: string): { email: string; name: string | null } {
  const decoded = cleanHeader(decodeEncodedWords(value));
  const angle = /<([^<>]+)>/.exec(decoded);
  if (angle) {
    const name = decoded.slice(0, angle.index).replace(/["']/g, "").trim();
    return { email: angle[1]!.trim().toLowerCase(), name: name || null };
  }
  // « adresse (Nom) » ou adresse nue ; en liste, la première seulement
  return { email: decoded.replace(/\(.*?\)/g, "").split(",")[0]!.trim().toLowerCase(), name: null };
}

/** Identifiants de message (<…>) d'un en-tête Message-ID / In-Reply-To / References. */
export function extractMessageIds(value: string | null | undefined): string[] {
  return [...(value ?? "").matchAll(/<[^<>\s]{1,300}>/g)].map((m) => m[0]);
}

/** Le premier Authentication-Results de Google atteste-t-il l'adresse `from` ? dmarc=pass suffit (il
 *  vérifie l'alignement avec le From) ; un dkim=pass seul ne vaut que si le domaine qui signe est
 *  celui du From (ou son parent) : l'attaquant qui signe avec son propre domaine ne passe pas. */
export function authenticatesSender(authResults: string, from: string): boolean {
  if (/\bdmarc=pass\b/i.test(authResults)) return true;
  const fromDomain = from.split("@")[1]?.toLowerCase() ?? "";
  if (!fromDomain) return false;
  for (const part of authResults.split(";")) {
    if (!/\bdkim=pass\b/i.test(part)) continue;
    const d = /\bheader\.(?:d|i)=@?(?:[^@\s;]*@)?([a-z0-9.-]+)/i.exec(part)?.[1]?.toLowerCase();
    if (d && (fromDomain === d || fromDomain.endsWith(`.${d}`))) return true;
  }
  return false;
}

export interface ParseOptions {
  /** `raw` est une chaîne « binaire » (un caractère par octet), telle que rendue par node/imap.mjs. */
  binary?: boolean;
  /** Le message a été coupé à la relève. */
  truncated?: boolean;
}

export function parseRawEmail(raw: string, options: ParseOptions = {}): ParsedEmail {
  const binary = options.binary === true;
  const truncated = options.truncated === true;
  const sep = raw.search(/\r?\n\r?\n/);
  const headerBlock = sep >= 0 ? raw.slice(0, sep) : raw;
  const body = sep >= 0 ? raw.slice(sep).replace(/^\r?\n\r?\n/, "") : "";
  const headers = unfoldHeaders(binary ? fixBinaryHeader(headerBlock) : headerBlock);

  const fromRaw = headers.get("from") ?? "";
  const { email: from, name: fromName } = parseAddress(fromRaw);
  const to = headers.get("to") ? parseAddress(headers.get("to")!).email : null;
  const deliveredTo = headers.get("delivered-to") ? parseAddress(headers.get("delivered-to")!).email : null;

  const autoSubmitted = (headers.get("auto-submitted") ?? "no").toLowerCase();
  const precedence = (headers.get("precedence") ?? "").toLowerCase();
  const isAutoGenerated =
    (autoSubmitted !== "" && autoSubmitted !== "no") ||
    ["bulk", "junk", "list", "auto_reply"].includes(precedence) ||
    headers.has("x-auto-response-suppress") ||
    headers.has("list-id");

  const collected: Collected = { plain: [], html: [], attachments: [] };
  collect(body, headers, collected, { binary, truncated }, 0);
  let text = (collected.plain.some((p) => p.trim() !== "") ? collected.plain : collected.html).join("\n\n").trim();
  if (text.length > MAX_TEXT_BODY) text = `${text.slice(0, MAX_TEXT_BODY)}\n[… message tronqué]`;

  const ids = extractMessageIds(headers.get("message-id"));
  const messageIdRaw = headers.get("message-id")?.trim();
  const refs = extractMessageIds(headers.get("references"));
  const dateMs = headers.get("date") ? Date.parse(headers.get("date")!) : Number.NaN;

  // Authentication-Results : seul le premier en-tête compte (celui que le serveur de réception
  // a posé en tête) et seulement s'il vient de Gmail ; un en-tête forgé par l'expéditeur est plus bas.
  const auth = headers.get("authentication-results") ?? "";
  const authServer = (auth.split(";")[0] ?? "").trim().toLowerCase();
  const senderAuthenticated = /(^|\.)google\.com$/.test(authServer) && authenticatesSender(auth, from);

  return {
    messageId: ids[0] ?? (messageIdRaw ? cleanHeader(messageIdRaw).slice(0, 300) || null : null),
    from,
    fromName: fromName ? fromName.slice(0, 200) : null,
    to,
    subject: cleanHeader(decodeEncodedWords(headers.get("subject") ?? "")).slice(0, 300),
    textBody: text,
    isAutoGenerated,
    inReplyTo: extractMessageIds(headers.get("in-reply-to"))[0] ?? null,
    references: refs.length ? refs.slice(-20).join(" ") : null,
    date: Number.isNaN(dateMs) ? null : new Date(dateMs).toISOString(),
    attachments: collected.attachments.slice(0, 50),
    senderAuthenticated,
    deliveredTo,
    truncated,
  };
}

