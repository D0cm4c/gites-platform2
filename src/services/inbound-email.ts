export interface InboundHooks {
  /** envoie l'accusé de réception (Email Worker reply en prod, stub en dev) */
  reply?: (subject: string, body: string) => Promise<void>;
  /** transfère le mail brut vers une adresse vérifiée */
  forward?: (to: string) => Promise<void>;
}

export interface InboundResult {
  stored: boolean;
  duplicate: boolean;
  id: number | null;
  propertyId: number;
  bookingRef: string | null;
  autoReplied: boolean;
  forwarded: boolean;
}

export async function processInboundEmail(
  db: D1Database,
  env: Env,
  parsed: ParsedEmail,
  hooks: InboundHooks = {},
  now: Date = new Date(),
): Promise<InboundResult> {
  const nowSql = sqlNow(now);

  // domaine destinataire : match sur l'adresse de contact, sinon 1er domaine
  const properties = await listProperties(db);
  const property =
    properties.find((p) => (p.contactEmail ?? "").toLowerCase() === (parsed.to ?? "").toLowerCase()) ?? properties[0];
  const propertyId = property?.id ?? 1;

  // rattachement : référence dans sujet/corps, sinon client par email
  let booking: BookingRow | null = null;
  const refMatch = /\b([A-Z]{2}-\d{4}-\d{3,})\b/.exec(`${parsed.subject} ${parsed.textBody}`);
  if (refMatch) booking = await getBookingByReference(db, refMatch[1]!);
  let guestId: number | null = booking?.guestId ?? null;
  if (!booking && parsed.from) {
    const guest = await db
      .prepare("SELECT id FROM guests WHERE lower(email) = ?1")
      .bind(parsed.from.toLowerCase())
      .first<{ id: number }>();
    if (guest) {
      guestId = guest.id;
      booking = (await bookingsForGuest(db, guest.id))[0] ?? null;
    }
  }

  // insertion (idempotente par Message-ID)
  const id = await insertInboundMessage(db, {
    propertyId,
    messageId: parsed.messageId,
    channel: "email",
    fromEmail: parsed.from || "inconnu",
    fromName: parsed.fromName,
    toEmail: parsed.to,
    subject: parsed.subject || "(sans objet)",
    bodyText: parsed.textBody,
    bookingId: booking?.id ?? null,
    guestId,
    receivedAt: nowSql,
  });
  if (id === null) {
    return { stored: false, duplicate: true, id: null, propertyId, bookingRef: booking?.reference ?? null, autoReplied: false, forwarded: false };
  }

  const settings = await getSettings(db, propertyId);

  // accusé de réception automatique — jamais à un mail automatique (anti-boucle)
  let autoReplied = false;
  if (settings.autoReplyEnabled && !parsed.isAutoGenerated && hooks.reply && parsed.from) {
    const body = settings.autoReplyText
      .replaceAll("{nom}", parsed.fromName ?? "")
      .replaceAll("{reference}", booking?.reference ?? "");
    const subject = parsed.subject ? `Re: ${parsed.subject}` : "Bien reçu — nous revenons vers vous";
    let status: "sent" | "failed" = "sent";
    try {
      await hooks.reply(subject, body);
      autoReplied = true;
      await db.prepare("UPDATE messages SET auto_replied = 1 WHERE id = ?1").bind(id).run();
    } catch {
      status = "failed";
    }
    await db
      .prepare(
        "INSERT INTO email_log (booking_id, to_email, subject, body_text, kind, status) VALUES (?1, ?2, ?3, ?4, 'auto_reply', ?5)",
      )
      .bind(booking?.id ?? null, parsed.from, subject, body, status)
      .run();
  }

  // transfert vers l'adresse personnelle configurée
  let forwarded = false;
  if (settings.emailForwardTo && hooks.forward) {
    try {
      await hooks.forward(settings.emailForwardTo);
      forwarded = true;
      await db.prepare("UPDATE messages SET forwarded = 1 WHERE id = ?1").bind(id).run();
    } catch {
      // le transfert peut échouer (adresse non vérifiée côté Email Routing) — le mail reste en boîte
    }
  }

  await audit(db, "public", "email.inbound", `inbound:${id}`, {
    from: parsed.from,
    subject: parsed.subject,
    booking: booking?.reference ?? null,
    autoReplied,
    forwarded,
  });

  return { stored: true, duplicate: false, id, propertyId, bookingRef: booking?.reference ?? null, autoReplied, forwarded };
}

// ---------------------------------------------------------------------------
// Construction d'une réponse MIME (pour message.reply en prod)
// ---------------------------------------------------------------------------

function encodeWordUtf8(text: string): string {
  if (/^[\x20-\x7e]*$/.test(text)) return text;
  const bytes = new TextEncoder().encode(text);
  let bin = "";
  for (const b of bytes) bin += String.fromCharCode(b);
  return `=?utf-8?B?${btoa(bin)}?=`;
}

export function buildReplyMime(
  fromEmail: string,
  toEmail: string,
  subject: string,
  body: string,
  inReplyTo: string | null,
): string {
  const bytes = new TextEncoder().encode(body);
  let bin = "";
  for (const b of bytes) bin += String.fromCharCode(b);
  const b64 = btoa(bin).replace(/(.{76})/g, "$1\r\n");
  const headers = [
    `From: ${fromEmail}`,
    `To: ${toEmail}`,
    `Subject: ${encodeWordUtf8(subject)}`,
    inReplyTo ? `In-Reply-To: ${inReplyTo}` : null,
    inReplyTo ? `References: ${inReplyTo}` : null,
    `Auto-Submitted: auto-replied`,
    `MIME-Version: 1.0`,
    `Content-Type: text/plain; charset=utf-8`,
    `Content-Transfer-Encoding: base64`,
  ].filter(Boolean);
  return headers.join("\r\n") + "\r\n\r\n" + b64 + "\r\n";
}
